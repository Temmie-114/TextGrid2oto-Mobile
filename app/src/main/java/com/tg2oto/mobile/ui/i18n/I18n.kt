    fun configure(userSetting: String?, systemEnglish: Boolean) {
        setting = userSetting
        systemIsEnglish = systemEnglish
    }

    val isEnglish: Boolean
        get() = when (setting) {
            "en" -> true
            "zh" -> false
            else -> systemIsEnglish
